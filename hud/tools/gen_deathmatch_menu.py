def tile(prefix: str, i: int, tabs: int) -> str:
    t, a, b = f"{prefix}{i}", "\t" * tabs, "\t" * (tabs + 1)
    return (
        f'{a}<Button id="{t}" class="dmm-t hidden">\n'
        f'{b}<Panel class="dmm-t-edge" hittest="false" />\n'
        f'{b}<Panel class="dmm-t-art" hittest="false" />\n'
        f'{b}<Panel class="dmm-t-lock" hittest="false" />\n'
        f'{b}<Label class="dmm-t-n" text="{{s:{t}_n}}" />\n'
        f'{b}<Label id="{t}_c" class="dmm-t-c hidden" text="{{s:{t}_c}}" />\n'
        f'{a}</Button>\n'
    )


def section(key: str, prefix: str, slots: int) -> str:
    out = [
        f'\t\t\t\t\t\t<Panel id="dmm_{key}sec" class="dmm-sec hidden" hittest="false">\n',
        f'\t\t\t\t\t\t\t<Panel class="dmm-sec-head" hittest="false">\n',
        f'\t\t\t\t\t\t\t\t<Label class="dmm-sec-k" text="{{s:dmm_{key}_k}}" />\n',
        f'\t\t\t\t\t\t\t\t<Panel class="fill" hittest="false" />\n',
        f'\t\t\t\t\t\t\t\t<Label class="dmm-saved-k" text="{{s:dmm_{key}_saved_k}}" />\n',
        f'\t\t\t\t\t\t\t\t<Label id="dmm_{key}_saved" class="dmm-saved" text="{{s:dmm_{key}_saved}}" />\n',
        f'\t\t\t\t\t\t\t</Panel>\n',
    ]
    for r in range(slots // TILES_PER_ROW):
        out.append(f'\t\t\t\t\t\t\t<Panel id="dmm_{key}row{r}" class="dmm-row hidden" hittest="false">\n')
        for c in range(TILES_PER_ROW):
            out.append(tile(prefix, r * TILES_PER_ROW + c, 8))
        out.append('\t\t\t\t\t\t\t</Panel>\n')
    out.append('\t\t\t\t\t\t</Panel>\n')
    return "".join(out)


def setting_row(c: int, r: int, tabs: int) -> str:
    row, a, b, d = f"dmm_c{c}_r{r}", "\t" * tabs, "\t" * (tabs + 1), "\t" * (tabs + 2)
    opts = "".join(
        f'{d}<Button id="{row}_o{o}" class="dmm-opt hidden"><Label class="dmm-opt-lbl" text="{{s:{row}_o{o}_t}}" /></Button>\n'
        for o in range(OPTION_SLOTS))
    return (
        f'{a}<Panel id="{row}" class="dmm-set hidden" hittest="false">\n'
        f'{b}<Label class="dmm-set-k" text="{{s:{row}_k}}" />\n'
        f'{b}<Label class="dmm-set-sc" text="{{s:{row}_sc}}" />\n'
        f'{b}<Panel class="dmm-opts" hittest="false">\n'
        f'{opts}'
        f'{b}</Panel>\n'
        f'{b}<Button id="{row}_go" class="dmm-go"><Label class="dmm-go-lbl" text="{{s:{row}_go_t}}" /></Button>\n'
        f'{a}</Panel>\n'
    )


