def build_art() -> str:
    lines = ["/* ---- art: generated by hud/tools/gen_deathmatch_menu.py, do not edit by hand ---- */\n"]
    for name, aspect in ASPECT.items():
        w = round(aspect * TILE_ART_H, 1)
        if w > 104:   # wider than the tile's inside: fit the width instead
            w, h = 104, round(104 / aspect, 1)
        else:
            h = TILE_ART_H
        lines.append(
            f'.w-{name} .dmm-t-art {{ width: {w:g}px; height: {h:g}px; background-texture-size: {round(w * 2)}px {round(h * 2)}px; '
            f'background-image: url("s2r://panorama/images/icons/equipment/{name}.vsvg"); }}\n')
    for name, aspect in UTILITY_ASPECT.items():
        w = round(aspect * UTILITY_H, 1)
        lines.append(
            f'.dmm-u.u-{name} {{ width: {w:g}px; background-texture-size: {round(w * 2)}px {UTILITY_H * 2}px; '
            f'background-image: url("s2r://panorama/images/icons/equipment/{name}.vsvg"); }}\n')
    lines.append("/* ---- end of generated art ---- */\n")
    return "".join(lines)


def main() -> None:
    XML.write_text(build_xml())
    css = CSS.read_text()
    block = build_art()
    pattern = re.compile(r"/\* ---- art: generated.*?/\* ---- end of generated art ---- \*/\n", re.S)
    css = pattern.sub(lambda _: block, css) if pattern.search(css) else css.rstrip("\n") + "\n\n" + block
    CSS.write_text(css)
    print(f"wrote {XML.relative_to(HUD)} and the art block of {CSS.relative_to(HUD)}")


if __name__ == "__main__":
    main()
