using CounterStrikeSharp.API.Core;
using Microsoft.Extensions.Logging;

using PanoramaManager;

namespace Deathmatch.Services;

/// <summary>One weapon tile. <see cref="Art"/> is a name from <see cref="MenuHud.Weapons"/>, or "" for none.</summary>
public sealed class MenuTile
{
    public string Art = "";
    public string Name = "";
    public bool Selected;
    public bool Locked;

    /// <summary>The limit in the corner: "1/3", "VIP", "OFF", or "" for none.</summary>
    public string Limit = "";
}

public sealed class MenuSection
{
    public bool Visible;
    public string Head = "";
    public string SavedKey = "";
    public string Saved = "";
    public List<MenuTile> Tiles = [];
}

public enum MenuRowKind { Head, Options, Go }

/// <summary>One settings row: a category heading, a preference with its option buttons, or another plugin's menu.</summary>
public sealed class MenuRow
{
    public MenuRowKind Kind;
    public string Label = "";
    public string Shortcut = "";
    public string Go = "";
    public List<(string Text, bool Selected)> Options = [];
}

/// <summary>Everything one viewer's menu says, already in their language.</summary>
public sealed class MenuView
{
    public string Title = "", Tag = "", NowKey = "", Now = "", NextKey = "", Next = "";
    public string[] TabNames = ["", "", ""];
    public int Tab;
    public bool SpawnsTab;

    // Weapons
    public List<(string Text, string Tone)> Chips = [];
    public string AlsoKey = "";
    public List<string> Utilities = [];
    public string Note = "";
    public bool Random;
    public MenuSection Primary = new(), Secondary = new();

    // Settings
    public List<MenuRow>[] Columns = [[], []];
    public string SettingsEmpty = "";

    // Spawns
    public string CtKey = "", Ct = "", TKey = "", T = "", Dirty = "";
    public string AddCt = "", AddT = "", Remove = "", Save = "", SpawnsHint = "";

    // Footer
    public string Status = "", StatusTone = "";
    public string Command = "", CommandText = "";
}

/// <summary>
/// The Deathmatch menu's panel: one mouse-driven card (hud/panorama/layout/custom_game/deathmatch_menu.xml in the
/// workshop addon, generated by hud/tools/gen_deathmatch_menu.py) for !gun, !dm and the spawns editor, instead of
/// the CenterHtmlMenus and the chat list. This class only draws a <see cref="MenuView"/> and reports clicks; what the
/// menu shows and what a click does is Functions/HudMenus.cs.
///
/// <para><b>Every draw writes the whole view, and only what changed reaches the client.</b> Each viewer keeps the
/// strings and classes last written to them, so the once-a-second redraw (the mode timer, the weapon limits) costs a
/// few writes. The cache is dropped whenever the panel starts from its authored state again: on open and after the
/// library rebuilt it (PanelAction.Restored).</para>
/// </summary>
public sealed class MenuHud : IDisposable
{
    private const string Layout = "panorama/layout/custom_game/deathmatch_menu.vxml_c";
    private const string RootId = "DeathmatchMenuRoot";

    public const int TabWeapons = 0, TabSettings = 1, TabSpawns = 2, Tabs = 3;

    // The pools in the layout (hud/tools/gen_deathmatch_menu.py)
    public const int PrimarySlots = 24, SecondarySlots = 12, TilesPerRow = 6;
    public const int ChipSlots = 5, UtilitySlots = 4;
    public const int ColumnSlots = 2, RowSlots = 9, OptionSlots = 6;

    // The heights in deathmatch_menu.css, for the body's bh-N class: change one, change both
    private const int StripHeight = 22, NoteHeight = 24, SectionHeight = 28, TileRowHeight = 59;
    private const int FirstHeadHeight = 26, HeadHeight = 36, RowHeight = 32, EmptyHeight = 20;
    private const int SpawnsHeight = 154;
    private const int StepPx = 20, MinStep = 8, MaxStep = 24;

    /// <summary>The w-&lt;weapon&gt; tile art classes the stylesheet has (weapon_ stripped).</summary>
    public static readonly HashSet<string> Weapons =
    [
        "ak47", "aug", "awp", "bizon", "cz75a", "deagle", "elite", "famas", "fiveseven", "g3sg1", "galilar", "glock",
        "hkp2000", "m249", "m4a1", "m4a1_silencer", "mac10", "mag7", "mp5sd", "mp7", "mp9", "negev", "nova", "p250",
        "p90", "revolver", "sawedoff", "scar20", "sg556", "ssg08", "tec9", "ump45", "usp_silencer", "xm1014",
    ];

    /// <summary>The u-&lt;item&gt; icons for what a mode also hands out.</summary>
    public static readonly HashSet<string> Utilities =
    [
        "flashbang", "hegrenade", "smokegrenade", "molotov", "incgrenade", "decoy", "healthshot", "taser", "knife",
    ];

    private static readonly string[] WeaponClasses = Weapons.Select(w => "w-" + w).ToArray();
    private static readonly string[] UtilityClasses = Utilities.Select(u => "u-" + u).ToArray();
    private static readonly string[] TabSteps = Enumerable.Range(0, Tabs).Select(i => "at-" + i).ToArray();
    private static readonly string[] HeightSteps = Enumerable.Range(MinStep, MaxStep - MinStep + 1).Select(i => "bh-" + i).ToArray();
    private static readonly string[] ChipTones = ["warn", "gold"];
    private static readonly string[] StatusTones = ["ok", "warn"];

    private sealed class Viewer
    {
        public readonly Dictionary<string, string> Vars = [];
        public readonly Dictionary<(string Panel, string Class), bool> Classes = [];

        /// <summary>One-of-many groups (a tile's art, the underline): the class that is on, null for none.</summary>
        public readonly Dictionary<(string Panel, string[] Group), string?> OneOf = [];
    }

    private readonly BasePlugin _plugin;
    private readonly Dictionary<int, Viewer> _viewers = [];
    private PanelHandle? _panel;

    /// <summary>A button in the card, by element id (the X is the library's).</summary>
    public event Action<CCSPlayerController, string>? Clicked;

    /// <summary>The library rebuilt this viewer's panel: draw it again.</summary>
    public event Action<CCSPlayerController>? Restored;

    /// <summary>The menu closed for this slot, however it happened.</summary>
    public event Action<int>? Closed;

    public MenuHud(BasePlugin plugin)
    {
        _plugin = plugin;
    }

    public bool Enabled => _panel != null;

    /// <summary>Spawns the layout once. A second Spawn would orphan the first entity, so this is guarded.</summary>
    public void Init()
    {
        if (_panel != null)
            return;

        try
        {
            Panorama.Init(_plugin);
            _panel = Panorama.Spawn(Layout, new LayoutContract
            {
                // Unique server-wide: dialog variables are keyed by panel id
                RootPanelId = RootId,
                RevealClass = "show",
                CloseButtonId = "dmm_close",
                RowCount = 0,
                CaptureInput = true,
                HideHud = HideHudFlags.None,
                SharedText = false,
            });
            _panel.OnEvent += OnPanelEvent;
            _plugin.Logger.LogInformation("Deathmatch menu ready");
        }
        catch (Exception ex)
        {
            // The plugin works without it: every caller opens the old center menus when Enabled is false
            _plugin.Logger.LogWarning("Deathmatch menu failed to start, using the center menus instead: {Message}", ex.Message);
            _panel = null;
        }
    }

    public void Dispose()
    {
        _panel?.Dispose();
        _panel = null;
        _viewers.Clear();
    }

    public bool IsOpenFor(CCSPlayerController player) =>
        _panel != null && _viewers.ContainsKey(player.Slot) && _panel.IsOpenFor(player);

    /// <summary>Opens the card for a player. False when it could not be opened, so the caller can use the old menu.</summary>
    public bool Open(CCSPlayerController player)
    {
        if (_panel == null)
            return false;

        _panel.Open(player);
        if (!_panel.IsOpenFor(player))
            return false;

        // A fresh session starts on the authored classes and no text
        _viewers[player.Slot] = new Viewer();
        return true;
    }

    public void Close(CCSPlayerController player) => _panel?.Close(player);

    /// <summary>A player left: drop the session and everything kept for the slot.</summary>
    public void Forget(int slot)
    {
        _viewers.Remove(slot);
        _panel?.Close(slot);
    }

    private void OnPanelEvent(PanelEvent e)
    {
        if (e.Player is not { IsValid: true } player)
            return;

        switch (e.Action)
        {
            case PanelAction.Close:
                _viewers.Remove(player.Slot);
                Closed?.Invoke(player.Slot);
                return;

            case PanelAction.Restored:
                if (!_viewers.ContainsKey(player.Slot))
                {
                    _panel?.Close(player);
                    return;
                }

                // The rebuilt panel has none of our text or classes any more
                _viewers[player.Slot] = new Viewer();
                Restored?.Invoke(player);
                return;

            case PanelAction.Button:
                if (_viewers.ContainsKey(player.Slot))
                    Clicked?.Invoke(player, e.ElementId);
                return;
        }
    }

    // ------------------------------------------------------------------ drawing

    public void Draw(CCSPlayerController player, MenuView view)
    {
        if (_panel == null || !_viewers.TryGetValue(player.Slot, out var v) || !_panel.IsOpenFor(player))
            return;

        // Header
        Var(player, v, "dmm_title", view.Title);
        Var(player, v, "dmm_tag", view.Tag);
        Var(player, v, "dmm_now_k", view.NowKey);
        Var(player, v, "dmm_now", view.Now);
        Var(player, v, "dmm_next_k", view.NextKey);
        Var(player, v, "dmm_next", view.Next);
        Cls(player, v, "dmm_next", "hidden", view.Next.Length == 0);

        // Tabs
        var tab = Math.Clamp(view.Tab, 0, Tabs - 1);
        for (var i = 0; i < Tabs; i++)
        {
            Var(player, v, $"dmm_tab{i}", view.TabNames[i]);
            Cls(player, v, $"dmm_tab{i}", "active", i == tab);
            Cls(player, v, $"dmm_pg{i}", "active", i == tab);
        }
        Cls(player, v, "dmm_tab2", "hidden", !view.SpawnsTab);
        OneOf(player, v, "dmm_bar", TabSteps[tab], TabSteps);

        DrawWeapons(player, v, view);
        DrawSettings(player, v, view);
        DrawSpawns(player, v, view);

        // Footer
        Var(player, v, "dmm_status", view.Status);
        OneOf(player, v, "dmm_status", view.StatusTone.Length > 0 ? view.StatusTone : null, StatusTones);
        Var(player, v, "dmm_cmd", view.Command);
        Var(player, v, "dmm_cmd_t", view.CommandText);

        OneOf(player, v, "dmm_body", HeightSteps[BodyStep(view) - MinStep], HeightSteps);
    }

    private void DrawWeapons(CCSPlayerController player, Viewer v, MenuView view)
    {
        Cls(player, v, "dmm_pg0", "rand", view.Random);

        for (var i = 0; i < ChipSlots; i++)
        {
            var id = $"dmm_chip{i}";
            var on = i < view.Chips.Count;
            Var(player, v, id, on ? view.Chips[i].Text : "");
            OneOf(player, v, id, on && view.Chips[i].Tone.Length > 0 ? view.Chips[i].Tone : null, ChipTones);
            Cls(player, v, id, "hidden", !on);
        }

        Var(player, v, "dmm_also_k", view.AlsoKey);
        Cls(player, v, "dmm_also", "hidden", view.Utilities.Count == 0);
        for (var i = 0; i < UtilitySlots; i++)
        {
            var id = $"dmm_u{i}";
            var art = i < view.Utilities.Count && Utilities.Contains(view.Utilities[i]) ? "u-" + view.Utilities[i] : null;
            OneOf(player, v, id, art, UtilityClasses);
            Cls(player, v, id, "hidden", art == null);
        }

        Var(player, v, "dmm_note", view.Note);
        Cls(player, v, "dmm_note", "hidden", view.Note.Length == 0);

        DrawSection(player, v, view.Primary, "p", PrimarySlots);
        DrawSection(player, v, view.Secondary, "s", SecondarySlots);
    }

    private void DrawSection(CCSPlayerController player, Viewer v, MenuSection section, string key, int slots)
    {
        Cls(player, v, $"dmm_{key}sec", "hidden", !section.Visible);
        Var(player, v, $"dmm_{key}_k", section.Head);
        Var(player, v, $"dmm_{key}_saved_k", section.SavedKey);
        Var(player, v, $"dmm_{key}_saved", section.Saved);

        var count = section.Visible ? Math.Min(section.Tiles.Count, slots) : 0;
        for (var r = 0; r < slots / TilesPerRow; r++)
            Cls(player, v, $"dmm_{key}row{r}", "hidden", r * TilesPerRow >= count);

        for (var i = 0; i < slots; i++)
        {
            var id = $"dmm_{key}{i}";
            if (i >= count)
            {
                Cls(player, v, id, "hidden", true);
                continue;
            }

            var tile = section.Tiles[i];
            var art = Weapons.Contains(tile.Art) ? "w-" + tile.Art : null;
            Var(player, v, $"{id}_n", tile.Name);
            Var(player, v, $"{id}_c", tile.Limit);
            OneOf(player, v, id, art, WeaponClasses);
            Cls(player, v, id, "sel", tile.Selected);
            Cls(player, v, id, "locked", tile.Locked);
            Cls(player, v, $"{id}_c", "hidden", tile.Limit.Length == 0);
            Cls(player, v, $"{id}_c", "full", tile.Locked);
            Cls(player, v, id, "hidden", false);
        }
    }

    private void DrawSettings(CCSPlayerController player, Viewer v, MenuView view)
    {
        var empty = view.Columns.All(c => c.Count == 0);
        Var(player, v, "dmm_set_empty", view.SettingsEmpty);
        Cls(player, v, "dmm_set_empty", "hidden", !empty);

        for (var c = 0; c < ColumnSlots; c++)
        {
            var rows = c < view.Columns.Length ? view.Columns[c] : [];
            for (var r = 0; r < RowSlots; r++)
            {
                var id = $"dmm_c{c}_r{r}";
                if (r >= rows.Count)
                {
                    Cls(player, v, id, "hidden", true);
                    continue;
                }

                var row = rows[r];
                Var(player, v, $"{id}_k", row.Label);
                Var(player, v, $"{id}_sc", row.Kind == MenuRowKind.Options ? row.Shortcut : "");
                Var(player, v, $"{id}_go_t", row.Kind == MenuRowKind.Go ? row.Go : "");
                Cls(player, v, id, "kind-head", row.Kind == MenuRowKind.Head);
                Cls(player, v, id, "kind-go", row.Kind == MenuRowKind.Go);

                for (var o = 0; o < OptionSlots; o++)
                {
                    var optionId = $"{id}_o{o}";
                    var on = row.Kind == MenuRowKind.Options && o < row.Options.Count;
                    Var(player, v, $"{optionId}_t", on ? row.Options[o].Text : "");
                    Cls(player, v, optionId, "sel", on && row.Options[o].Selected);
                    Cls(player, v, optionId, "hidden", !on);
                }

                Cls(player, v, id, "hidden", false);
            }
        }
    }

    private void DrawSpawns(CCSPlayerController player, Viewer v, MenuView view)
    {
        Var(player, v, "dmm_sp_ct_k", view.CtKey);
        Var(player, v, "dmm_sp_ct", view.Ct);
        Var(player, v, "dmm_sp_t_k", view.TKey);
        Var(player, v, "dmm_sp_t", view.T);
        Var(player, v, "dmm_sp_dirty", view.Dirty);
        Cls(player, v, "dmm_sp_dirty", "hidden", view.Dirty.Length == 0);
        Var(player, v, "dmm_sp_addct", view.AddCt);
        Var(player, v, "dmm_sp_addt", view.AddT);
        Var(player, v, "dmm_sp_rm", view.Remove);
        Var(player, v, "dmm_sp_save", view.Save);
        Var(player, v, "dmm_sp_hint", view.SpawnsHint);
    }

    /// <summary>
    /// The body's height step: the tallest page this viewer can switch to, in 20px steps, so a tab switch never
    /// resizes the card. From the heights in deathmatch_menu.css.
    /// </summary>
    private static int BodyStep(MenuView view)
    {
        static int Section(MenuSection s, int slots) =>
            s.Visible ? SectionHeight + (Math.Min(s.Tiles.Count, slots) + TilesPerRow - 1) / TilesPerRow * TileRowHeight : 0;

        var weapons = StripHeight + (view.Note.Length > 0 ? NoteHeight : 0)
            + Section(view.Primary, PrimarySlots) + Section(view.Secondary, SecondarySlots);

        var settings = EmptyHeight;
        foreach (var column in view.Columns)
        {
            var height = 0;
            for (var i = 0; i < column.Count && i < RowSlots; i++)
                height += column[i].Kind == MenuRowKind.Head ? (i == 0 ? FirstHeadHeight : HeadHeight) : RowHeight;
            settings = Math.Max(settings, height);
        }

        var content = Math.Max(weapons, settings);
        if (view.SpawnsTab)
            content = Math.Max(content, SpawnsHeight);

        return Math.Clamp((content + StepPx - 1) / StepPx, MinStep, MaxStep);
    }

    // ------------------------------------------------------------------ writes, only the changes

    private void Var(CCSPlayerController player, Viewer v, string name, string value)
    {
        if (v.Vars.TryGetValue(name, out var old) && old == value)
            return;

        v.Vars[name] = value;
        _panel!.SetVariableFor(player, name, value);
    }

    private void Cls(CCSPlayerController player, Viewer v, string id, string cls, bool on)
    {
        if (v.Classes.TryGetValue((id, cls), out var old) && old == on)
            return;

        v.Classes[(id, cls)] = on;
        _panel!.SetClassFor(player, id, cls, on);
    }

    /// <summary>
    /// Puts <paramref name="cls"/> on (null: none) and takes the group's previous one off. A fresh viewer starts with
    /// none of the group on, as the layout is authored, so only the new class is written.
    /// </summary>
    private void OneOf(CCSPlayerController player, Viewer v, string id, string? cls, string[] group)
    {
        v.OneOf.TryGetValue((id, group), out var old);
        if (old == cls)
            return;

        if (old != null)
            _panel!.SetClassFor(player, id, old, false);
        if (cls != null)
            _panel!.SetClassFor(player, id, cls, true);

        v.OneOf[(id, group)] = cls;
    }
}
